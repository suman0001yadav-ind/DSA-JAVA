// TIME AND COMPLEXITY :--

// 1. Definition :--

// Time Complexity measures how the running time of an algorithm increases with the size of input
// (n).

// 2)  Common Notations (Big-O)

// O(1) - Constant Time
// O(log n) - Logarithmic Time
// O(n) - Linear Time
// O(n log n) - Linearithmic Time
// O(n²) - Quadratic Time

// 3. Example
// for(int i = 0; i < n; i++) { print(i); }
// This loop runs n times → Time Complexity = O(n)

// 4. Importance
// Helps compare efficiency of algorithms and choose the fastest solution for large inputs.